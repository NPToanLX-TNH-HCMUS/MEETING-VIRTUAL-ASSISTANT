"""
Integration test suite: Audio Recording to Speech-to-Text Pipeline (Audio <-> STT).

Validates the meeting recording & transcription lifecycle:
1. Microphone capture via Recorder generating 44.1kHz WAV.
2. Binary wave verification and API dispatch via ElevenLabsTranscriber.
3. Resilient error handling when audio streams or network disconnect.
"""

from pathlib import Path
from unittest.mock import MagicMock, patch

import numpy as np
import pytest
from scipy.io.wavfile import write

from backend.audio.recorder import (
    CHANNELS,
    MAX_SECONDS,
    SAMPLE_RATE,
    Recorder,
)
from backend.speech_to_text.transcriber import (
    AudioTranscriptionError,
    ElevenLabsTranscriber,
)


@pytest.fixture
def recorder() -> Recorder:
    """Fixture providing a fresh Recorder instance."""
    return Recorder()


@pytest.fixture
def transcriber() -> ElevenLabsTranscriber:
    """Fixture providing an STT transcriber with a mock API key."""
    return ElevenLabsTranscriber(api_key="mock-test-elevenlabs-key")


class TestAudioToSTTIntegration:
    """Integration test suite linking Audio Recorder output with STT ingestion."""

    def test_recorded_wav_seamlessly_transcribed_by_stt(
        self,
        recorder: Recorder,
        transcriber: ElevenLabsTranscriber,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        """
        INT-AUD-01: Verifies that audio generated by Recorder matches the exact
        format requirements of ElevenLabsTranscriber and produces a formatted transcript physically.
        """
        # Ensure temporary outputs like transcript.json are isolated within tmp_path
        monkeypatch.chdir(tmp_path)

        # Arrange
        meeting_audio = tmp_path / "live_meeting.wav"
        transcript_out = tmp_path / "live_transcript.txt"

        # Part 1: Simulate Recorder producing a valid WAV file
        dummy_audio_buffer = np.zeros((MAX_SECONDS * SAMPLE_RATE, CHANNELS), dtype=np.int16)
        with patch("sounddevice.rec", return_value=dummy_audio_buffer), \
             patch("sounddevice.stop"), \
             patch("time.monotonic", side_effect=[100.0, 102.0, 102.0]):
            recorder.start()
            recorded_duration = recorder.stop(path=str(meeting_audio))

        assert meeting_audio.exists()
        assert recorded_duration == 2.0

        # Part 2: Transcriber consumes the WAV file
        mock_api_response = {
            "text": "Hello team, today we will discuss Segment Tree.",
            "words": [
                {"word": "Hello", "start": 0.1, "end": 0.4, "speaker_id": "speaker_0"},
                {"word": "team", "start": 0.5, "end": 0.8, "speaker_id": "speaker_0"},
            ],
        }

        # Allow genuine file system writing for transcript validation
        with patch("backend.speech_to_text.transcriber.requests.post") as mock_post:
            mock_post.return_value.ok = True
            mock_post.return_value.json.return_value = mock_api_response

            result_text = transcriber.transcribe_file(
                audio_path=meeting_audio,
                output_path=transcript_out,  # Pass Path object directly to ensure path methods
            )

        # Part 3: Assert integration success on both returned text and physical file
        assert "Segment Tree" in result_text
        mock_post.assert_called_once()
        assert transcript_out.exists(), "Transcript file was not physically created"
        assert "Segment Tree" in transcript_out.read_text(encoding="utf-8")

    def test_empty_recording_rejected_by_stt_without_api_call(
        self, transcriber: ElevenLabsTranscriber, tmp_path: Path
    ) -> None:
        """
        INT-AUD-02: Zero-frame audio files must be blocked by the transcriber
        before any external HTTP API requests are made.
        """
        # Arrange
        empty_wav = tmp_path / "empty_recording.wav"
        empty_data = np.zeros(0, dtype=np.int16)
        write(str(empty_wav), SAMPLE_RATE, empty_data)

        # Act & Assert
        with patch("backend.speech_to_text.transcriber.requests.post") as mock_post:
            with pytest.raises(ValueError, match="Audio file is empty"):
                transcriber.transcribe_file(empty_wav)

            # Strictly guarantee no remote API request was dispatched
            mock_post.assert_not_called()

    def test_audio_pipeline_preserves_audio_file_on_network_timeout(
        self, transcriber: ElevenLabsTranscriber, tmp_path: Path
    ) -> None:
        """
        INT-AUD-03: If STT fails due to network outage, the original recorded audio
        file must remain intact on disk for future retry mechanisms.
        """
        # Arrange
        meeting_audio = tmp_path / "retryable_audio.wav"
        dummy_audio = np.zeros(SAMPLE_RATE, dtype=np.int16)
        write(str(meeting_audio), SAMPLE_RATE, dummy_audio)

        import requests
        
        # Act & Assert
        with patch(
            "backend.speech_to_text.transcriber.requests.post",
            side_effect=requests.Timeout("Connection timed out"),
        ):
            with pytest.raises(AudioTranscriptionError, match="Transcription request timed out"):
                transcriber.transcribe_file(meeting_audio)

        assert meeting_audio.exists(), "Original audio file must remain preserved for retries"
