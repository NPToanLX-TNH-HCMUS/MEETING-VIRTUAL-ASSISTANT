    def test_stt_transcript_ingested_by_analyzer_pipeline(
        self, transcriber: ElevenLabsTranscriber, tmp_path: Path
    ) -> None:
        """
        INT-STT-ANA-01: Verifies that a diarized transcript generated by STT is cleanly
        consumed by MeetingContentAnalyzer without schema or encoding mismatch.
        """
        # Arrange: Generate a realistic STT transcript artifact
        audio_path = tmp_path / "discussion.wav"
        transcript_path = tmp_path / "discussion_transcript.txt"
        write(str(audio_path), SAMPLE_RATE, np.zeros(SAMPLE_RATE, dtype=np.int16))

        mock_stt_payload = {
            "text": "An Bình sẽ hoàn thành module STT trước ngày 15/11 nha. Cả nhóm đồng ý nhé.",
            "words": [
                {"word": "An", "start": 0.1, "end": 0.3, "speaker_id": "speaker_0"},
                {"word": "Bình", "start": 0.3, "end": 0.6, "speaker_id": "speaker_0"},
            ],
        }
        mock_post = MagicMock(ok=True)
        mock_post.json.return_value = mock_stt_payload

        with patch("backend.speech_to_text.transcriber.requests.post", return_value=mock_post):
            raw_transcript = transcriber.transcribe_file(
                audio_path=audio_path, output_path=transcript_path
            )

        assert transcript_path.exists()
        assert "An Bình" in raw_transcript

