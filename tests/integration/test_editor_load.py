"""
Integration test suite: Content Analyzer to Document Editor (Analyzer <-> Editor).

Validates that extracted meeting minutes and audited action items persisted in
post_meeting storage are cleanly loaded into the Document editor buffer for human review.
"""

from pathlib import Path

import pytest

from backend.document.document import Document
from backend.meeting_manager.storage_manager import StorageManager


@pytest.fixture
def storage(tmp_path: Path) -> StorageManager:
    """Fixture providing an isolated StorageManager rooted in tmp_path."""
    return StorageManager(root_dir=tmp_path)


@pytest.fixture
def editor() -> Document:
    """Fixture providing a fresh Document editor instance."""
    return Document()


class TestAnalyzerToEditorIntegration:
    """Validates the presentation and human-in-the-loop resolution of analyzed minutes."""

    def test_analyzed_markdown_loads_into_editor_with_unconfirmed_tags(
        self, storage: StorageManager, editor: Document, tmp_path: Path
    ) -> None:
        """
        INT-ANA-ED-01: Verifies that Markdown generated by the Analyzer containing
        [UNCONFIRMED] and [CONFIRMED] audit flags loads cleanly from post_meeting
        storage into the Document buffer with 100% UTF-8 fidelity.
        """
        # Arrange: Initialize meeting directories and write simulated Analyzer output
        meeting_id = "meeting_post_review_01"
        storage.create_meeting_directory(meeting_id)
        minutes_dir = tmp_path / meeting_id / "post_meeting" / "meeting_minutes"
        report_path = minutes_dir / "draft_minutes.md"

        analyzer_output = (
            "# BIÊN BẢN HỌP: THẢO LUẬN SEGMENT TREE\n\n"
            "## 1. Nội Dung Chính (Main Content)\n"
            "- Thống nhất kiến trúc 3 giai đoạn Pre-In-Post cho hệ thống MIA.\n\n"
            "## 2. Các Ý Tưởng Mở (Ideas)\n"
            "- [UNCONFIRMED] Thêm hình động minh họa trực quan (Đề xuất: Đăng Khôi - Chưa chốt)\n\n"
            "## 3. Nhiệm Vụ Cần Làm (Action Items)\n"
            "- [ ] [UNCONFIRMED] Viết tài liệu kiểm thử | Phụ trách: Chưa rõ | Hạn: 15/11/2026\n"
            "- [x] [CONFIRMED] Xây dựng Storage Manager | Phụ trách: Phước Toàn | Hạn: 10/11/2026\n"
        )
        report_path.write_text(analyzer_output, encoding="utf-8")

        # Act: Load artifact into Document Editor
        loaded_content = editor.load(str(report_path))

        # Assert: Editor state transitions and preserves all audit tags and diacritics
        assert editor.has_path is True
        assert editor.path == str(report_path)
        assert "[UNCONFIRMED]" in loaded_content
        assert "[CONFIRMED]" in loaded_content
        assert loaded_content == analyzer_output

    def test_editor_resolves_unconfirmed_task_and_saves_back(
        self, storage: StorageManager, editor: Document, tmp_path: Path
    ) -> None:
        """
        INT-ANA-ED-02: Simulates the Human-in-the-Loop workflow where a reviewer
        edits an [UNCONFIRMED] task to assign an owner ('Khánh Hưng'), upgrades its
        status to [CONFIRMED], and persists both in-place and final signed-off copies.
        """
        # Arrange
        meeting_id = "meeting_hitl_signoff"
        storage.create_meeting_directory(meeting_id)
        action_items_dir = tmp_path / meeting_id / "post_meeting" / "action_items"

        draft_path = action_items_dir / "pending_tasks.md"
        final_path = action_items_dir / "final_approved_tasks.md"

        initial_draft = (
            "# Danh Sách Công Việc\n"
            "- [ ] [UNCONFIRMED] Hoàn thiện báo cáo LaTeX | Phụ trách: NULL | Hạn: 12/11/2026\n"
        )
        draft_path.write_text(initial_draft, encoding="utf-8")
        editor.load(str(draft_path))

        # Act 1: Human reviewer assigns owner and saves in-place
        resolved_text = (
            "# Danh Sách Công Việc\n"
            "- [x] [CONFIRMED] Hoàn thiện báo cáo LaTeX | Phụ trách: Khánh Hưng | Hạn: 12/11/2026\n"
        )
        editor.save(resolved_text)

        # Assert 1: Draft file updated in-place
        assert draft_path.read_text(encoding="utf-8") == resolved_text
        assert "UNCONFIRMED" not in draft_path.read_text(encoding="utf-8")

        # Act 2: Export/Save As finalized record
        editor.save(resolved_text, path=str(final_path))

        # Assert 2: Final signed-off file persisted and bound to editor
        assert final_path.exists()
        assert editor.path == str(final_path)
        assert final_path.read_text(encoding="utf-8") == resolved_text
        